export default async function (fastify, opts) {
    fastify.get('', {
        schema: {
            tags: ['Metadata'],
            summary: 'List Available Formula Methods',
            description: 'Returns all built-in HyperFormula functions with descriptions, categories, syntax, and example formulas',
            response: {
                200: MethodsResponseSchema
            }
        }
    }, async (req, reply) => {
        try {
            // Build a temporary HyperFormula instance to get function information
            const hf = HyperFormula.buildEmpty({
                licenseKey: 'gpl-v3'
            });
            
            try {
                // Get all registered function names
                const functionNames = hf.getRegisteredFunctionNames();
                
                // Get function registry for metadata
                const functionRegistry = hf._functionRegistry;
                
                // Build method list with metadata
                const methods = functionNames.map(name => {
                    // Get function metadata if available
                    let metadata = null;
                    try {
                        metadata = functionRegistry.getMetadata(name);
                    } catch (e) {
                        // Some functions may not have metadata
                    }
                    
                    // Build parameters array
                    const parameters = [];
                    if (metadata && metadata.parameters) {
                        metadata.parameters.forEach((param, index) => {
                            parameters.push({
                                name: `arg${index + 1}`,
                                type: param.argumentType || 'ANY',
                                optional: param.optionalArg || false,
                                description: param.defaultValue !== undefined 
                                    ? `Optional, default: ${param.defaultValue}` 
                                    : undefined
                            });
                        });
                    }
                    
                    // Handle variable arguments
                    if (metadata && metadata.repeatLastArgs && parameters.length > 0) {
                        const lastParam = parameters[parameters.length - 1];
                        lastParam.name = `${lastParam.name}, ...`;
                    }
                    
                    return {
                        name: name,
                        category: getCategory(name),
                        description: generateDescription(name, metadata),
                        syntax: generateSyntax(name, metadata?.parameters),
                        parameters: parameters,
                        examples: getExamples(name),
                        isVolatile: metadata?.isVolatile || false
                    };
                });
                
                // Sort methods by category then by name
                methods.sort((a, b) => {
                    if (a.category !== b.category) {
                        return a.category.localeCompare(b.category);
                    }
                    return a.name.localeCompare(b.name);
                });
                
                // Get unique categories
                const categories = [...new Set(methods.map(m => m.category))].sort();
                
                return reply.send({
                    status: 'success',
                    methods: methods,
                    count: methods.length,
                    categories: categories
                });
            } finally {
                // Always destroy the HyperFormula instance
                hf.destroy();
            }
        } catch (error) {
            req.log.error(error);
            return reply.status(500).send({
                status: 'error',
                message: 'Failed to retrieve available methods'
            });
        }
    });
}
