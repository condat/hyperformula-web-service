/**
 * Generate a syntax string from function metadata
 */
function generateSyntax(name, parameters) {
    if (!parameters || parameters.length === 0) {
        return `=${name}()`;
    }
    
    const paramStrings = parameters.map((param, index) => {
        const optional = param.optionalArg || param.defaultValue !== undefined;
        const paramName = param.argumentType ? param.argumentType.toLowerCase() : `arg${index + 1}`;
        return optional ? `[${paramName}]` : paramName;
    });
    
    return `=${name}(${paramStrings.join(', ')})`;
}

/**
 * Get category for a function
 */
function getCategory(name) {
    return FUNCTION_CATEGORIES[name] || 'Other';
}

/**
 * Get example formulas for a function
 */
function getExamples(name) {
    return EXAMPLE_FORMULAS[name] || [`=${name}()`, `=${name}(...)`];
}

